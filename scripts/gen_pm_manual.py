# ─── Doc template with TOC support + header/footer ───
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))
            self.canv.bookmarkPage(key)
            self.canv.addOutlineEntry(text, key, level=level, closed=False)

def draw_page_furniture(canvas, doc):
    canvas.saveState()
    # header
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 0.55 * inch, DOC_TITLE.upper())
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 0.62 * inch, PAGE_W - MARGIN, PAGE_H - 0.62 * inch)
    # footer
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 0.62 * inch, PAGE_W - MARGIN, 0.62 * inch)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 0.45 * inch, '3Boxes HRMS  |  Version 1.0  |  September 2026')
    canvas.drawRightString(PAGE_W - MARGIN, 0.45 * inch, str(doc.page))
    canvas.restoreState()

# ─── Helpers ───
def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)

def make_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def embed_image(path, max_width=None, max_height=None):
    if max_width is None: max_width = AVAIL_W
    if max_height is None: max_height = MAX_IMG_H
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow if ow > max_width else 1.0,
                max_height / oh if oh > max_height else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)

def callout(kind, title, text):
    border = {'note': ACCENT, 'warning': SEM_WARNING, 'tip': ICON,
              'error': SEM_ERROR, 'info': SEM_INFO}.get(kind, ACCENT)
    inner = [[Paragraph('<b>%s</b>' % title, S['callout_title'])],
             [Paragraph(text, S['callout_body'])]]
    t = Table(inner, colWidths=[AVAIL_W - 8], hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('LINEBEFORE', (0, 0), (0, -1), 3, border),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, 0), 8),
        ('BOTTOMPADDING', (0, -1), (-1, -1), 8),
        ('TOPPADDING', (0, 1), (-1, 1), 0),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ]))
    return [Spacer(1, 6)] + safe_keep_together([t]) + [Spacer(1, 8)]

def nav_path(path_text):
    inner = [[Paragraph('NAVIGATION:  ' + path_text, S['nav'])]]
    t = Table(inner, colWidths=[AVAIL_W - 8], hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), SECTION_BG),
        ('BOX', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]))
    return [Spacer(1, 4)] + safe_keep_together([t]) + [Spacer(1, 8)]

def build_table(headers, rows, ratios, caption_text=None, bold_col0=False):
    assert abs(sum(ratios) - 1.0) < 0.01, 'ratios must sum to 1'
    col_w = [r * AVAIL_W * 0.98 for r in ratios]
    assert sum(col_w) <= AVAIL_W + 0.5
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in headers]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = S['tdb'] if (bold_col0 and i == 0) else S['td']
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for r in range(1, len(data)):
        style.append(('BACKGROUND', (0, r), (-1, r),
                      TABLE_STRIPE if r % 2 == 1 else colors.white))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 10)]
    if caption_text:
        cap = Paragraph(caption_text, S['caption'])
        if len(rows) <= 13:
            out += safe_keep_together([t, cap])
        else:
            out += [t, cap]
    else:
        out += safe_keep_together([t]) if len(rows) <= 13 else [t]
    out.append(Spacer(1, 10))
    return out

def block_to_flowables(blk):
    kind = blk[0]
    out = []
    if kind == 'h2':
        out.append(make_heading(blk[1], S['h2'], level=1))
    elif kind == 'h3':
        out.append(Paragraph('<b>%s</b>' % blk[1], S['h3']))
    elif kind == 'p':
        out.append(Paragraph(blk[1], S['body']))
    elif kind == 'bullets':
        for b in blk[1]:
            out.append(Paragraph(b, S['bullet'], bulletText='\u2022'))
        out.append(Spacer(1, 4))
    elif kind == 'steps':
        for i, stp in enumerate(blk[1], 1):
            out.append(Paragraph('<font color="#288a59"><b>%d.</b></font>  %s' % (i, stp), S['step']))
        out.append(Spacer(1, 4))
    elif kind == 'table':
        _, headers, rows, ratios = blk[0], blk[1], blk[2], blk[3]
        cap = blk[4] if len(blk) > 4 else None
        out += build_table(headers, rows, ratios, cap, bold_col0=True)
    elif kind == 'callout':
        out += callout(blk[1], blk[2], blk[3])
    elif kind == 'nav':
        out += nav_path(blk[1])
    elif kind == 'img':
        img = embed_image(os.path.join(ASSETS, blk[1]))
        cap = Paragraph(blk[2], S['caption'])
        out.append(Spacer(1, 8))
        out += safe_keep_together([img, cap])
        out.append(Spacer(1, 8))
    elif kind == 'diagram':
        img = embed_image(os.path.join(ASSETS, blk[1]))
        cap = Paragraph(blk[2], S['caption'])
        out.append(Spacer(1, 8))
        out += safe_keep_together([img, cap])
        out.append(Spacer(1, 8))
    return out

def chapter(num, title, blocks):
    """H1 chapter heading + accent rule + blocks, with orphan prevention."""
    flows = []
    flows.append(CondPageBreak(H1_THRESHOLD))
    flows.append(Spacer(1, 10))
    head = make_heading('%d.  %s' % (num, title), S['h1'], level=0)
    rule = HRFlowable(width='100%', thickness=1.6, color=ACCENT,
                      spaceBefore=2, spaceAfter=12)
    flows += safe_keep_together([head, rule])
    # bind first content block with the heading pair when lightweight
    if blocks:
        first = block_to_flowables(blocks[0])
        rest = []
        if first and isinstance(first[0], Paragraph):
            flows = flows[:-2] + safe_keep_together([head, rule, first[0]]) + first[1:]
        else:
            flows += first
        for b in blocks[1:]:
            flows += block_to_flowables(b)
    return flows

def build(chapters, out_path=OUT_BODY):
    doc = TocDocTemplate(out_path, pagesize=A4,
                         leftMargin=MARGIN, rightMargin=MARGIN,
                         topMargin=TOP_MARGIN, bottomMargin=BOTTOM_MARGIN,
                         title=DOC_TITLE, author='Z.ai', creator='Z.ai',
                         subject='User manual and standard operating procedures for the 3Boxes HRMS Project Management module')
    story = []
    toc = TableOfContents()
    toc.levelStyles = [toc_l0, toc_l1]
    story.append(Paragraph('<b>Table of Contents</b>', S['toc_title']))
    story.append(HRFlowable(width='100%', thickness=1.6, color=ACCENT, spaceAfter=14))
    story.append(toc)
    story.append(PageBreak())
    for ch in chapters:
        story += chapter(ch['num'], ch['title'], ch['blocks'])
    doc.multiBuild(story, onFirstPage=draw_page_furniture, onLaterPages=draw_page_furniture)
    print('body built:', out_path)

